#!/usr/bin/env python3
"""Generate sw.js (precache list + content hash) and tools/deploy-list.txt.

Run from anywhere:
    python3 tools/build-sw.py

Re-run after any runtime file change so iPad/PWA clients pick up the new
version on the next launch. This script does not deploy anything.
"""
from __future__ import annotations

import hashlib
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SCHEMA = "v1"

EXCLUDE_DIRS = {
    "samples",
    "screenshots-review",
    "backups_round14",
    "backups_round15",
    "backups_round21",
    "backups_round22",
    "tools",
}

EXCLUDE_FILES = {
    "run-review.mjs",
    "README.md",
    "serve.sh",
    ".gitignore",
    "sw.js",
}


def should_publish(rel: Path) -> bool:
    if any(part in EXCLUDE_DIRS for part in rel.parts):
        return False
    if rel.name in EXCLUDE_FILES:
        return False
    if rel.name.startswith("."):
        return False
    return True


def collect_files() -> list[Path]:
    files = [p for p in ROOT.rglob("*") if p.is_file()]
    rels = [p.relative_to(ROOT) for p in files]
    return sorted((r for r in rels if should_publish(r)), key=lambda r: r.as_posix())


def version_hash(files: list[Path]) -> str:
    h = hashlib.sha256()
    h.update(SCHEMA.encode())
    h.update(b"\0")
    for rel in files:
        h.update(rel.as_posix().encode())
        h.update(b"\0")
        data = (ROOT / rel).read_bytes()
        h.update(str(len(data)).encode())
        h.update(b"\0")
        h.update(data)
        h.update(b"\0")
    return h.hexdigest()[:12]


def js_string_array(items: list[str]) -> str:
    lines = [f'  "{item}"' for item in items]
    return "[\n" + ",\n".join(lines) + "\n]"


SW_TEMPLATE = """\
/* Generated by tools/build-sw.py — do not edit by hand. Re-run the script after file changes. */
const CACHE_NAME = {cache_name};
const PRECACHE = {precache};

function toUrl(path) {{
  return new URL(path, self.registration.scope).href;
}}

async function precache() {{
  const cache = await caches.open(CACHE_NAME);
  for (const path of PRECACHE) {{
    const url = toUrl(path);
    const res = await fetch(url, {{ cache: "reload" }});
    if (!res.ok) {{
      throw new Error("Failed to precache " + url + " (" + res.status + ")");
    }}
    await cache.put(url, res);
  }}
}}

async function dropOldCaches() {{
  const keys = await caches.keys();
  await Promise.all(
    keys
      .filter((key) => key !== CACHE_NAME)
      .map((key) => caches.delete(key))
  );
}}

self.addEventListener("install", (event) => {{
  event.waitUntil(precache().then(() => self.skipWaiting()));
}});

self.addEventListener("activate", (event) => {{
  // Activate the new worker, but do not claim open clients. The current
  // check-in session keeps running on the already-loaded page; the next
  // launch (or reload) is served from the new cache.
  event.waitUntil(dropOldCaches());
}});

self.addEventListener("fetch", (event) => {{
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  event.respondWith((async () => {{
    const cache = await caches.open(CACHE_NAME);
    const hit = await cache.match(req, {{ ignoreSearch: true }});
    if (hit) return hit;

    const isNav =
      req.mode === "navigate" ||
      (req.headers.get("accept") || "").includes("text/html");
    if (isNav) {{
      const fallback =
        (await cache.match(toUrl("./index.html"), {{ ignoreSearch: true }})) ||
        (await cache.match(toUrl("./"), {{ ignoreSearch: true }}));
      if (fallback) return fallback;
    }}

    try {{
      return await fetch(req);
    }} catch (err) {{
      return new Response("Offline", {{ status: 503, statusText: "Offline" }});
    }}
  }})());
}});
"""


def write_deploy_list(files: list[Path], total_bytes: int, version: str) -> None:
    dest = ROOT / "tools" / "deploy-list.txt"
    lines = [
        "# Files to publish to GitHub Pages (app root = this list).",
        f"# Generated by tools/build-sw.py  cache=self-checkin-{SCHEMA}-{version}",
        f"# {len(files)} files, {total_bytes} bytes ({total_bytes / (1024 * 1024):.2f} MB).",
        "# Do not publish: samples/, screenshots-review/, backups_round14/, backups_round15/, backups_round21/, backups_round22/, tools/, run-review.mjs,",
        "# README.md, serve.sh, .gitignore.",
        "# This file is a listing only; nothing is uploaded by the script.",
        "",
    ]
    for rel in files:
        size = (ROOT / rel).stat().st_size
        lines.append(f"{rel.as_posix()}\t{size}")
    dest.write_text("\n".join(lines) + "\n", encoding="utf-8")


def main() -> int:
    files = collect_files()
    if not files:
        print("No files to precache", file=sys.stderr)
        return 1
    version = version_hash(files)
    cache_name = f"self-checkin-{SCHEMA}-{version}"
    precache_paths = ["./"] + [f"./{rel.as_posix()}" for rel in files]
    # Keep ./index.html even if "./" already covers the document.
    sw = SW_TEMPLATE.format(
        cache_name=f'"{cache_name}"',
        precache=js_string_array(precache_paths),
    )
    (ROOT / "sw.js").write_text(sw, encoding="utf-8")
    total_bytes = sum((ROOT / rel).stat().st_size for rel in files)
    write_deploy_list(files, total_bytes, version)
    print(f"Wrote sw.js  cache={cache_name}")
    print(f"Precache: {len(precache_paths)} entries, {total_bytes} bytes ({total_bytes / (1024 * 1024):.2f} MB)")
    print(f"Deploy list: tools/deploy-list.txt ({len(files)} files)")
    for rel in files:
        print(f"  {rel.as_posix()}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
